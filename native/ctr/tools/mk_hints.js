// mk_hints.js: app/www/hints.js (the story steps the phone and Windows apps use) as C tables, so the 3DS keeps one source.
//   node mk_hints.js <hints.js> <out hintdata.h>
// Each step: text (the leading "?" kept: the 3DS shows it as the app does, without it), room, x, y, z, its items (none: a place
// step) and the guide line drawn in the editor (waypoints x, y, z, room).
const fs = require('fs'), vm = require('vm');
const src = fs.readFileSync(process.argv[2], 'utf8'), ctx = {};
vm.runInNewContext(src + '\n;this.HINTS=HINTS;', ctx);
const H = ctx.HINTS;
const q = s => '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\u2018\u2019]/g, "'").replace(/[\u201c\u201d]/g, '\\"')
  .replace(/\u2026/g, '...').replace(/[\u2013\u2014]/g, '-').replace(/[^\x20-\x7e]/g, '') + '"';
let o = '/* generated by tools/mk_hints.js from app/www/hints.js: do not edit */\n';
let ways = '', steps = '', lv = 'static const TrLevelSteps HINTS[16] = {\n';
for (let n = 0; n < 16; n++) {
  const L = H[n] || [];
  L.forEach((s, i) => {
    const it = s[5] == null || s[5] < 0 ? [] : [].concat(s[5]);
    if (it.length > 8) throw new Error('level ' + n + ' step ' + i + ': more than 8 items');
    const w = s[6] || [];
    if (w.length) ways += `static const int32_t W_${n}_${i}[][4] = {${w.map(p => `{${p.map(v => Math.round(v)).join(',')}}`).join(',')}};\n`;
    steps += (i ? '' : `static const TrStep S_${n}[] = {\n`) +
      ` {${q(s[0])},${s[1]},${Math.round(s[2])},${Math.round(s[3])},${Math.round(s[4])},${it.length},{${it.length ? it.join(',') : '0'}},${w.length},${w.length ? 'W_' + n + '_' + i : 'NULL'}},\n` +
      (i === L.length - 1 ? '};\n' : '');
  });
  lv += L.length ? ` {S_${n}, ${L.length}},\n` : ' {NULL, 0},\n';
}
o += ways + steps + lv + '};\n';
fs.writeFileSync(process.argv[3], o);
console.log('ok', process.argv[3], Object.keys(H).length, 'levels');
